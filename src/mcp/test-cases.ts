import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { AutomationPlan, JiraRequirements, TestCase } from './types';
import { validateTicketId } from './jira';
import { analyzeFramework, readFrameworkIndex } from './framework';

function createCases(ticketId: string, requirements: JiraRequirements): TestCase[] {
  if (requirements.acceptanceCriteria.length === 0) {
    throw new Error(`Jira issue ${ticketId} has no acceptance criteria. Add explicit criteria before generating tests.`);
  }
  const categories: TestCase['category'][] = ['positive', 'negative', 'edge'];
  return requirements.acceptanceCriteria.flatMap((criterion, index) => {
    const acceptanceCriterionId = `${ticketId}-AC${index + 1}`;
    return categories.map((category): TestCase => ({
      id: `${acceptanceCriterionId}-${category.toUpperCase()}`,
      acceptanceCriterionId,
      category,
      title: `${category[0].toUpperCase()}${category.slice(1)}: ${criterion}`,
      steps: category === 'positive'
        ? [`Perform the valid user flow required by: ${criterion}`]
        : category === 'negative'
          ? [`Try an invalid or missing input relevant to: ${criterion}`]
          : [`Exercise the boundary or repeated-use condition relevant to: ${criterion}`],
      expectedResult: category === 'positive'
        ? criterion
        : category === 'negative'
          ? 'The invalid attempt is rejected without unintended state changes.'
          : 'The boundary condition is handled without a crash or unintended state changes.',
      reviewRequired: true,
      automationPlan: null,
    }));
  });
}

function parseTestCases(value: unknown): TestCase[] {
  const isTestCase = (item: unknown): item is TestCase => {
    if (!item || typeof item !== 'object' || Array.isArray(item)) return false;
    const candidate = item as Record<string, unknown>;
    return typeof candidate.id === 'string'
      && typeof candidate.acceptanceCriterionId === 'string'
      && ['positive', 'negative', 'edge'].includes(String(candidate.category))
      && typeof candidate.title === 'string'
      && Array.isArray(candidate.steps)
      && candidate.steps.every((step) => typeof step === 'string')
      && typeof candidate.expectedResult === 'string'
      && typeof candidate.reviewRequired === 'boolean'
      && (candidate.automationPlanSource === undefined || candidate.automationPlanSource === 'local-rule')
      && (candidate.automationPlan === null || candidate.automationPlan === undefined
        || (typeof candidate.automationPlan === 'object' && !Array.isArray(candidate.automationPlan)));
  };
  if (!Array.isArray(value) || value.length === 0 || !value.every(isTestCase)) {
    throw new Error('Test case file has an invalid or empty testCases array.');
  }
  return value;
}

const GENERATED_SPEC_MARKER = '// Generated by the local Jira pipeline; edits are regenerated.';

async function writeNewFile(root: string, relative: string, content: string, replaceMarkedGenerated = false): Promise<boolean> {
  const absolute = path.resolve(root, relative);
  if (!absolute.startsWith(`${path.resolve(root)}${path.sep}`)) throw new Error('Generated file path is outside the repository.');
  await mkdir(path.dirname(absolute), { recursive: true });
  try {
    await writeFile(absolute, content, { encoding: 'utf8', flag: 'wx' });
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
  }
  const existing = await readFile(absolute, 'utf8');
  if (existing === content) return false;
  if (replaceMarkedGenerated && relative.startsWith('tests/generated/')
    && existing.startsWith(`${GENERATED_SPEC_MARKER}\n`)) {
    await writeFile(absolute, content, 'utf8');
    return true;
  }
  throw new Error(`Refusing to overwrite existing file: ${relative}`);
}

function sameTestCaseDraft(existing: TestCase, draft: TestCase): boolean {
  return existing.id === draft.id
    && existing.acceptanceCriterionId === draft.acceptanceCriterionId
    && existing.category === draft.category
    && existing.title === draft.title
    && JSON.stringify(existing.steps) === JSON.stringify(draft.steps)
    && existing.expectedResult === draft.expectedResult;
}

async function writeTestCaseFile(
  root: string,
  relative: string,
  document: {
    ticketId: string;
    title: string;
    acceptanceCriteria: Array<{ id: string; text: string }>;
    testCases: TestCase[];
  },
): Promise<boolean> {
  const absolute = path.resolve(root, relative);
  if (!absolute.startsWith(`${path.resolve(root)}${path.sep}`)) throw new Error('Generated file path is outside the repository.');
  await mkdir(path.dirname(absolute), { recursive: true });
  const content = `${JSON.stringify(document, null, 2)}\n`;
  try {
    await writeFile(absolute, content, { encoding: 'utf8', flag: 'wx' });
    return true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
  }

  const existing = JSON.parse(await readFile(absolute, 'utf8')) as {
    ticketId?: unknown;
    title?: unknown;
    acceptanceCriteria?: unknown;
    testCases?: unknown;
  };
  if (existing.ticketId !== document.ticketId || existing.title !== document.title
    || JSON.stringify(existing.acceptanceCriteria) !== JSON.stringify(document.acceptanceCriteria)) {
    throw new Error(`Refusing to overwrite test cases that no longer match Jira issue ${document.ticketId}.`);
  }
  const existingCases = parseTestCases(existing.testCases);
  if (existingCases.length !== document.testCases.length
    || existingCases.some((testCase, index) => !sameTestCaseDraft(testCase, document.testCases[index]))) {
    throw new Error(`Refusing to overwrite edited test-case drafts for ${document.ticketId}.`);
  }
  return false;
}

export async function generateTestCases(
  root: string,
  requestedId: string,
  requirements: JiraRequirements,
): Promise<{ path: string; count: number; cases: TestCase[]; created: boolean }> {
  const ticketId = validateTicketId(requestedId);
  if (validateTicketId(requirements.ticketId) !== ticketId) {
    throw new Error(`Requirements ticket ID does not match ${ticketId}.`);
  }
  const cases = createCases(ticketId, requirements);
  const relative = `test-cases/${ticketId}.json`;
  const created = await writeTestCaseFile(root, relative, {
    ticketId,
    title: requirements.title,
    acceptanceCriteria: requirements.acceptanceCriteria.map((text, index) => ({
      id: `${ticketId}-AC${index + 1}`,
      text,
    })),
    testCases: cases,
  });
  return { path: relative, count: cases.length, cases, created };
}

function inferLocalAutomationPlan(criterion: string, isHomePageRequirement: boolean): AutomationPlan | undefined {
  if (!isHomePageRequirement) return undefined;
  const labels = quotedLabelsFromCriterion(criterion);
  if (!labels.length) return undefined;
  if (labels.length === 1 && /\b(?:button|link)\b/i.test(criterion) && labels[0].toUpperCase() === 'JOIN NOW') {
    return {
      pageObject: 'homePage',
      actions: [{ method: 'goto' }],
      assertion: {
        kind: 'linkVisible',
        expected: 'Selenium Online Training',
        href: 'https://www.toolsqa.com/selenium-training/',
      },
    };
  }
  if (labels.length === 1 && /\b(?:button|link)\b/i.test(criterion)) {
    return {
      pageObject: 'homePage',
      actions: [{ method: 'goto' }],
      assertion: { kind: 'textVisible', expected: labels[0] },
    };
  }
  if (labels.length > 1
    && /\b(?:divs?|cards?|tiles?|sections?)\b/i.test(criterion)
    && /\b(?:present|visible|displayed)\b/i.test(criterion)) {
    return {
      pageObject: 'homePage',
      actions: [{ method: 'goto' }],
      assertion: { kind: 'textsVisible', expected: labels },
    };
  }
  return undefined;
}

export async function prepareLocalAutomationPlans(
  root: string,
  requestedId: string,
  requirements: JiraRequirements,
): Promise<{ cases: TestCase[]; updated: boolean }> {
  const ticketId = validateTicketId(requestedId);
  if (validateTicketId(requirements.ticketId) !== ticketId) {
    throw new Error(`Requirements ticket ID does not match ${ticketId}.`);
  }
  const absolute = path.resolve(root, 'test-cases', `${ticketId}.json`);
  const saved = JSON.parse(await readFile(absolute, 'utf8')) as {
    ticketId?: unknown;
    acceptanceCriteria?: unknown;
    testCases?: unknown;
    [key: string]: unknown;
  };
  if (saved.ticketId !== ticketId) throw new Error(`Test case file does not belong to ${ticketId}.`);
  const criteria = requirements.acceptanceCriteria.map((text, index) => ({
    id: `${ticketId}-AC${index + 1}`,
    text,
  }));
  if (JSON.stringify(saved.acceptanceCriteria) !== JSON.stringify(criteria)) {
    throw new Error(`Test-case acceptance criteria for ${ticketId} do not match the current Jira issue; refusing to auto-plan stale cases.`);
  }
  const criteriaById = new Map(criteria.map((criterion) => [criterion.id, criterion.text]));
  const isHomePageRequirement = /\b(?:home\s?page|homepage|demoqa)\b/i.test([
    requirements.title,
    ...requirements.acceptanceCriteria,
  ].join('\n'));
  const cases = parseTestCases(saved.testCases);
  let updated = false;
  const planned = cases.map((testCase) => {
    const criterion = criteriaById.get(testCase.acceptanceCriterionId);
    if (!criterion) throw new Error(`Test case ${testCase.id} references an unknown acceptance criterion.`);
    const automationPlan = inferLocalAutomationPlan(criterion, isHomePageRequirement);
    if (!automationPlan) {
      throw new Error(
        `No safe local automation plan can be inferred for ${testCase.id}; supported criteria need either one quoted button/link label or multiple quoted homepage card/div labels marked present or visible.`,
      );
    }
    const existingPlan = testCase.automationPlan;
    const legacyLocalPlan = testCase.reviewRequired === false
      && existingPlan?.pageObject === 'homePage'
      && Array.isArray(existingPlan.actions)
      && existingPlan.actions.length === 1
      && existingPlan.actions[0]?.method === 'goto'
      && existingPlan.assertion?.kind === 'textVisible'
      && existingPlan.assertion.expected === quotedLabelsFromCriterion(criterion)[0];
    if (existingPlan
      && testCase.automationPlanSource !== 'local-rule'
      && !legacyLocalPlan) return testCase;
    if (testCase.automationPlanSource === 'local-rule'
      && JSON.stringify(existingPlan) === JSON.stringify(automationPlan)) return testCase;
    updated = true;
    return { ...testCase, reviewRequired: false, automationPlan, automationPlanSource: 'local-rule' as const };
  });
  if (updated) {
    await writeFile(absolute, `${JSON.stringify({ ...saved, testCases: planned }, null, 2)}\n`, 'utf8');
  }
  return { cases: planned, updated };
}

function quotedLabelsFromCriterion(criterion: string): string[] {
  return [...criterion.matchAll(/"([^"]+)"|“([^”]+)”|'([^']+)'|‘([^’]+)’/g)]
    .map((match) => (match[1] ?? match[2] ?? match[3] ?? match[4] ?? '').trim())
    .filter(Boolean);
}

function assertKnownPlan(
  plan: AutomationPlan,
  pageNames: Set<string>,
  methods: Set<string>,
): void {
  if (!plan || typeof plan.pageObject !== 'string' || !Array.isArray(plan.actions)
    || !plan.assertion || !['textVisible', 'titleContains', 'linkVisible', 'textsVisible'].includes(plan.assertion.kind)) {
    throw new Error('Automation plan must include actions and a supported assertion.');
  }
  if (!/^[A-Za-z_$][\w$]*$/.test(plan.pageObject) || !pageNames.has(plan.pageObject)) {
    throw new Error(`Automation plan references unknown page object "${plan.pageObject}". Register page objects in PageManager first.`);
  }
  if (plan.actions.length === 0) throw new Error(`Automation plan for ${plan.pageObject} has no actions.`);
  for (const action of plan.actions) {
    if (!action || typeof action.method !== 'string' || !/^[A-Za-z_$][\w$]*$/.test(action.method)
      || !methods.has(`${plan.pageObject}.${action.method}`)) {
      throw new Error(`Automation plan references an unindexed method on ${plan.pageObject}.`);
    }
    if (action.args !== undefined && (!Array.isArray(action.args) || action.args.some((arg) => typeof arg !== 'string'))) {
      throw new Error('Automation action arguments must be strings.');
    }
  }
  if (plan.assertion.kind === 'linkVisible') {
    const href = new URL(plan.assertion.href);
    if (!['http:', 'https:'].includes(href.protocol)) throw new Error('A link-visible assertion href must use HTTP or HTTPS.');
  } else if (plan.assertion.kind === 'textsVisible') {
    if (!Array.isArray(plan.assertion.expected) || !plan.assertion.expected.length
      || plan.assertion.expected.some((text) => typeof text !== 'string' || !text.trim())) {
      throw new Error('A texts-visible assertion must include non-empty expected labels.');
    }
  } else if (typeof plan.assertion.expected !== 'string' || !plan.assertion.expected.trim()) {
    throw new Error('Automation assertion expected text cannot be empty.');
  }
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function renderSpec(ticketId: string, cases: TestCase[]): string {
  const lines = [
    GENERATED_SPEC_MARKER,
    "import { test, expect } from '../../src/fixtures/test';",
    '',
    `test.describe(${quote(`${ticketId} acceptance criteria`)}, () => {`,
  ];
  for (const testCase of cases) {
    const plan = testCase.automationPlan!;
    lines.push(`  test(${quote(testCase.title)}, async ({ page, pages }) => {`);
    for (const action of plan.actions) {
      const args = (action.args ?? []).map(quote).join(', ');
      lines.push(`    await pages.${plan.pageObject}.${action.method}(${args});`);
    }
    if (plan.assertion.kind === 'textVisible') {
      lines.push(`    await expect(page.getByText(${quote(plan.assertion.expected)}, { exact: true })).toBeVisible();`);
    } else if (plan.assertion.kind === 'linkVisible') {
      lines.push(`    const trainingLink = page.getByRole('link', { name: ${quote(plan.assertion.expected)}, exact: true });`);
      lines.push('    await expect(trainingLink).toBeVisible();');
      lines.push(`    await expect(trainingLink).toHaveAttribute('href', ${quote(plan.assertion.href)});`);
    } else if (plan.assertion.kind === 'textsVisible') {
      for (const expected of plan.assertion.expected) {
        lines.push(`    await expect(page.getByText(${quote(expected)}, { exact: true })).toBeVisible();`);
      }
    } else {
      lines.push(`    await expect.poll(() => page.title()).toContain(${quote(plan.assertion.expected)});`);
    }
    lines.push('  });');
  }
  lines.push('});', '');
  return lines.join('\n');
}

export async function generateAutomationScript(
  root: string,
  requestedId: string,
): Promise<{ paths: string[]; generated: boolean }> {
  const ticketId = validateTicketId(requestedId);
  await analyzeFramework(root);
  const saved = JSON.parse(await readFile(path.join(root, 'test-cases', `${ticketId}.json`), 'utf8')) as {
    ticketId?: unknown;
    testCases?: unknown;
  };
  if (saved.ticketId !== ticketId) throw new Error(`Test case file does not belong to ${ticketId}.`);
  const cases = parseTestCases(saved.testCases);
  const index = await readFrameworkIndex(root);
  const pageClasses = new Map<string, string>();
  const methods = new Set<string>();
  for (const symbol of index.reusable) {
    const registeredPage = symbol.name.match(/^PageManager\.(\w+)$/);
    if (registeredPage) pageClasses.set(registeredPage[1], symbol.signature);
  }
  for (const [property, pageClass] of pageClasses) {
    for (const symbol of index.reusable) {
      if (symbol.name.startsWith(`${pageClass}.`)) {
        methods.add(`${property}.${symbol.name.slice(pageClass.length + 1)}`);
      }
    }
  }
  const pageNames = new Set(pageClasses.keys());
  const missingPlans = cases.filter((testCase) => !testCase.automationPlan);
  if (missingPlans.length) {
    throw new Error(
      `${missingPlans.length} test cases need reviewed automationPlan entries in test-cases/${ticketId}.json. ` +
      'Use registered PageManager objects and methods; the server will not invent selectors or assertions.',
    );
  }
  for (const testCase of cases) assertKnownPlan(testCase.automationPlan!, pageNames, methods);
  const relative = `tests/generated/${ticketId}.spec.ts`;
  const generated = await writeNewFile(root, relative, renderSpec(ticketId, cases), true);
  return { paths: [relative], generated };
}

export async function readTestCases(root: string, requestedId: string): Promise<TestCase[]> {
  const ticketId = validateTicketId(requestedId);
  const parsed = JSON.parse(await readFile(path.join(root, 'test-cases', `${ticketId}.json`), 'utf8')) as {
    ticketId?: unknown;
    testCases?: unknown;
  };
  if (parsed.ticketId !== ticketId) throw new Error(`Test case file does not belong to ${ticketId}.`);
  return parseTestCases(parsed.testCases);
}
